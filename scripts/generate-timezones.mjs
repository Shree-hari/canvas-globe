// Regenerates the IANA timezone → coordinate table used to place the viewer's
// marker without a permission prompt or a network call. Run with `npm run data`.
// Source: the tz database (public domain).
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data");
const BASE = "https://raw.githubusercontent.com/eggert/tz/main/";

/** ISO 6709: ±DDMM±DDDMM or ±DDMMSS±DDDMMSS. Returns [lon, lat] in degrees. */
function parseCoordinates(text) {
  const long = text.length > 11;
  const latRaw = text.slice(0, long ? 7 : 5);
  const lonRaw = text.slice(long ? 7 : 5);
  const dms = (s, degreeDigits) => {
    const sign = s[0] === "-" ? -1 : 1;
    const body = s.slice(1);
    const deg = Number(body.slice(0, degreeDigits));
    const min = Number(body.slice(degreeDigits, degreeDigits + 2));
    const sec = body.length > degreeDigits + 2 ? Number(body.slice(degreeDigits + 2)) : 0;
    return sign * (deg + min / 60 + sec / 3600);
  };
  return [dms(lonRaw, 3), dms(latRaw, 2)];
}

const hundredths = (v) => Math.round(v * 100);

export async function generateTimezones() {
  console.log("→ tz database (zone1970.tab + backward)");
  const [tab, backward] = await Promise.all([
    fetch(`${BASE}zone1970.tab`).then((r) => r.text()),
    fetch(`${BASE}backward`).then((r) => r.text()),
  ]);

  const zones = [];
  const known = new Set();
  for (const line of tab.split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [codes, coords, name] = line.split("\t");
    if (!name) continue;
    const [lon, lat] = parseCoordinates(coords);
    zones.push(`${name}|${hundredths(lon)}|${hundredths(lat)}|${codes.split(",")[0]}`);
    known.add(name);
  }

  const aliases = [];
  for (const line of backward.split("\n")) {
    if (!line.startsWith("Link")) continue;
    const parts = line.split(/\s+/);
    const target = parts[1], alias = parts[2];
    if (alias && known.has(target) && !known.has(alias)) aliases.push(`${alias}>${target}`);
  }

  const body =
    `// Generated by scripts/generate-timezones.mjs. Do not edit.\n` +
    `// Source: the IANA tz database (public domain).\n` +
    `// "zone|lon|lat|country", coordinates in hundredths of a degree.\n` +
    `export const zoneTable = ${JSON.stringify(zones.join(";"))};\n` +
    `export const zoneAliases = ${JSON.stringify(aliases.join(";"))};\n`;

  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, "timezones.js"), body);
  console.log(`  ${zones.length} zones · ${aliases.length} aliases · ${Math.round(body.length / 1024)} KB`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateTimezones().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
