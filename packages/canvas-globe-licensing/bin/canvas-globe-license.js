#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";

const DEFAULT_ENDPOINT = "https://canvasglobe.swiftools.com/api/license/activate";
const TOKEN_MODULE = "src/license-data.js";
const STATE_FILE = join(".canvas-globe", "license.json");

function help() {
  console.log(`CanvasGlobe licensing

Usage:
  canvas-globe-license activate
  canvas-globe-license info
  canvas-globe-license token
  canvas-globe-license help

Environment:
  CANVAS_GLOBE_LICENSE_KEY       Commercial key from CanvasGlobe
  CANVAS_GLOBE_ACTIVATION_TOKEN  Existing offline token, recommended for CI
  CANVAS_GLOBE_LICENSE_ENDPOINT  Activation endpoint override
  CANVAS_GLOBE_PROJECT           Optional project label shown in the license portal`);
}

function packageRoot(cwd) {
  const require = createRequire(join(cwd, "package.json"));
  try {
    return dirname(require.resolve("canvas-globe/package.json"));
  } catch {
    throw new Error("canvas-globe is not installed in this project");
  }
}

function readCheckoutKey(cwd) {
  const fromEnvironment = process.env.CANVAS_GLOBE_LICENSE_KEY?.trim();
  if (fromEnvironment) return fromEnvironment;
  const path = join(cwd, "canvas-globe-license.txt");
  if (existsSync(path)) return readFileSync(path, "utf8").trim();
  throw new Error(
    "No license key found. Set CANVAS_GLOBE_LICENSE_KEY or add canvas-globe-license.txt to the project root.",
  );
}

function tokenPath(cwd) {
  return join(packageRoot(cwd), TOKEN_MODULE);
}

function installedVersion(cwd) {
  return JSON.parse(readFileSync(join(packageRoot(cwd), "package.json"), "utf8")).version;
}

function decodePayload(token) {
  try {
    return JSON.parse(Buffer.from(token.split(".")[0], "base64url").toString("utf8"));
  } catch {
    return null;
  }
}

function writeActivation(cwd, token, persist = true) {
  const source = `// Generated by canvas-globe-licensing. Do not commit this file.\nexport const ACTIVATED_LICENSE_TOKEN = ${JSON.stringify(token)};\n`;
  writeFileSync(tokenPath(cwd), source, { encoding: "utf8", mode: 0o600 });
  if (persist) {
    const statePath = join(cwd, STATE_FILE);
    mkdirSync(dirname(statePath), { recursive: true });
    writeFileSync(statePath, `${JSON.stringify({ activationToken: token }, null, 2)}\n`, { encoding: "utf8", mode: 0o600 });
  }
}

function reusableActivation(cwd) {
  const environmentToken = process.env.CANVAS_GLOBE_ACTIVATION_TOKEN?.trim();
  if (environmentToken) return { token: environmentToken, persist: false };
  const statePath = join(cwd, STATE_FILE);
  if (!existsSync(statePath)) return null;
  try {
    const token = JSON.parse(readFileSync(statePath, "utf8")).activationToken;
    const payload = decodePayload(token);
    const notExpired = !payload?.expiresAt || Date.parse(payload.expiresAt) > Date.now();
    if (typeof token === "string" && payload?.maxVersion === installedVersion(cwd) && notExpired) {
      return { token, persist: false };
    }
  } catch {
    return null;
  }
  return null;
}

function hasActivation(cwd) {
  const source = readFileSync(tokenPath(cwd), "utf8");
  return !/ACTIVATED_LICENSE_TOKEN\s*=\s*null/.test(source);
}

function savedActivation(cwd) {
  const statePath = join(cwd, STATE_FILE);
  if (!existsSync(statePath)) {
    throw new Error("No saved activation token found. Run canvas-globe-license activate first.");
  }
  const token = JSON.parse(readFileSync(statePath, "utf8")).activationToken;
  if (typeof token !== "string" || !decodePayload(token)) {
    throw new Error("The saved activation token is invalid. Activate again.");
  }
  return token;
}

async function activate(cwd) {
  const reusable = reusableActivation(cwd);
  if (reusable) {
    writeActivation(cwd, reusable.token, reusable.persist);
    console.log("CanvasGlobe license activation restored.");
    console.log("Run your application build now.");
    return;
  }
  const licenseKey = readCheckoutKey(cwd);
  const endpoint = process.env.CANVAS_GLOBE_LICENSE_ENDPOINT?.trim() || DEFAULT_ENDPOINT;
  const project = process.env.CANVAS_GLOBE_PROJECT?.trim() || resolve(cwd).split(/[\\/]/).pop();
  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ licenseKey, project, packageVersion: installedVersion(cwd) }),
  });
  const result = await response.json().catch(() => null);
  if (!response.ok || !result?.activationToken) {
    throw new Error(result?.message || `License activation failed with HTTP ${response.status}`);
  }
  writeActivation(cwd, result.activationToken);
  console.log(`CanvasGlobe license activated${result.plan ? ` for ${result.plan}` : ""}.`);
  console.log("Run your application build now.");
}

async function main() {
  const command = process.argv[2] || "help";
  const cwd = process.cwd();
  if (command === "help" || command === "--help" || command === "-h") return help();
  if (command === "info") {
    console.log(hasActivation(cwd) ? "CanvasGlobe license is activated." : "CanvasGlobe license is not activated.");
    return;
  }
  if (command === "token") {
    console.error("Treat this activation token as a secret. Store it only in your CI secret manager or no-build configuration.");
    console.log(savedActivation(cwd));
    return;
  }
  if (command === "activate") return activate(cwd);
  throw new Error(`Unknown command: ${command}`);
}

main().catch((error) => {
  console.error(`canvas-globe-license: ${error.message}`);
  process.exitCode = 1;
});
